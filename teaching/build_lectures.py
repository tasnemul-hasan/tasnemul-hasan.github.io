"""Generate the lecture pages of the Teaching section from teaching/lectures.yml.

Usage (from the site folder):
    python teaching/build_lectures.py

Requires PyYAML (pip install pyyaml). The script:
  1. checks lectures.yml (numbering 1..N, unique IDs/slugs, Drive ID format, filters),
  2. rewrites teaching/lectures/<slug>.qmd for every lecture,
  3. warns about stale .qmd files in teaching/lectures/ that no longer match an entry.
The landing page (teaching/index.qmd) lists the generated pages automatically.
"""
import html
import pathlib
import re
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "lectures"
FILTERS = {"sysid", "nn", "fuzzy", "anfis", "apps"}
DRIVE_ID = re.compile(r"^[A-Za-z0-9_-]{25,}$")


def slides_urls(fid):
    return (f"https://drive.google.com/file/d/{fid}/preview",
            f"https://docs.google.com/presentation/d/{fid}/edit")


def check(lectures):
    errors = []
    nums = [lec["number"] for lec in lectures]
    if nums != list(range(1, len(lectures) + 1)):
        errors.append(f"lecture numbers must run 1..{len(lectures)} in order, got {nums}")
    for key in ("id", "slug", "slides-id"):
        vals = [lec[key] for lec in lectures]
        if len(set(vals)) != len(vals):
            errors.append(f"duplicate {key} values")
    for lec in lectures:
        n = lec["number"]
        for key in ("id", "slug", "title", "category", "summary", "slides-id", "outline", "filters"):
            if not lec.get(key):
                errors.append(f"lecture {n}: missing {key}")
        if not DRIVE_ID.match(str(lec.get("slides-id", ""))):
            errors.append(f"lecture {n}: slides-id does not look like a Drive file ID")
        if not set(lec.get("filters", [])) <= FILTERS:
            errors.append(f"lecture {n}: unknown filter in {lec.get('filters')}")
        if not str(lec.get("slug", "")).startswith(f"{n:02d}-"):
            errors.append(f"lecture {n}: slug should start with {n:02d}-")
        words = len(str(lec.get("summary", "")).split())
        if not 15 <= words <= 40:
            print(f"note: lecture {n} summary has {words} words (target 20-35)")
    return errors


def page(lec, prev, nxt):
    e = html.escape
    num = f"{lec['number']:02d}"
    preview, original = slides_urls(lec["slides-id"])
    fm = {
        "title": lec["title"],
        "pagetitle": f"Lecture {num}: {lec['title']}",
        "description": lec["summary"],
        "lecture": num,
        "lecture-id": lec["id"],
        "category": lec["category"],
        "topics": "|".join(lec["filters"]),
        "slides-id": lec["slides-id"],
        "slides-url": original,
        "css": "../../assets/teaching.css",
    }
    out = ["---", "# Generated by teaching/build_lectures.py from teaching/lectures.yml. Edit the YAML, not this file.",
           yaml.safe_dump(fm, sort_keys=False, allow_unicode=True, width=1000).strip(), "---", ""]
    out += [
        '```{=html}',
        '<header class="lec-head">',
        '  <a class="lec-back" href="../index.html">&larr; All lectures</a>',
        f'  <p class="lec-eyebrow"><span class="lec-num">Lecture {num}</span><span class="lec-cat">{e(lec["category"])}</span></p>',
        f'  <h1 class="lec-title">{e(lec["title"])}</h1>',
        f'  <p class="lec-summary">{e(lec["summary"])}</p>',
        '</header>',
        '<figure class="lec-viewer">',
        '  <div class="lecture-slide-container">',
        f'    <iframe src="{preview}" title="Lecture {num} slides: {e(lec["title"])}" loading="lazy" allowfullscreen referrerpolicy="strict-origin-when-cross-origin"></iframe>',
        '  </div>',
        '  <figcaption class="lec-links">',
        f'    <a class="btn btn-primary btn-sm" href="{original}" target="_blank" rel="noopener">Open presentation <span aria-hidden="true">&nearr;</span><span class="visually-hidden"> (opens in a new tab)</span></a>',
        '    <span>If the viewer does not load, open the original presentation on Google Drive.</span>',
        '  </figcaption>',
        '</figure>',
        '```',
        '',
        '## Lecture outline',
        '',
        '::: {.lec-outline}',
    ]
    for group in lec["outline"]:
        out += ['::: {.lec-group}', f"### {group['heading']}", ""]
        out += [f"- {item}" for item in group["items"]]
        out += [":::", ""]
    out += [":::", "", "```{=html}", '<nav class="lec-nav" aria-label="Lecture navigation">']
    if prev:
        out.append(f'  <a class="prev" href="{prev["slug"]}.html"><span>&larr; Lecture {prev["number"]:02d}</span>{e(prev["title"])}</a>')
    else:
        out.append('  <span class="prev" aria-hidden="true"></span>')
    out.append('  <a class="all" href="../index.html">All lectures</a>')
    if nxt:
        out.append(f'  <a class="next" href="{nxt["slug"]}.html"><span>Lecture {nxt["number"]:02d} &rarr;</span>{e(nxt["title"])}</a>')
    else:
        out.append('  <span class="next" aria-hidden="true"></span>')
    out += ["</nav>", "```", ""]
    return "\n".join(out)


def main():
    data = yaml.safe_load((HERE / "lectures.yml").read_text(encoding="utf-8"))
    lectures = data["lectures"]
    errors = check(lectures)
    if errors:
        print("lectures.yml has problems:\n  " + "\n  ".join(errors))
        sys.exit(1)
    OUT.mkdir(exist_ok=True)
    wanted = set()
    for i, lec in enumerate(lectures):
        prev = lectures[i - 1] if i > 0 else None
        nxt = lectures[i + 1] if i + 1 < len(lectures) else None
        path = OUT / f"{lec['slug']}.qmd"
        path.write_text(page(lec, prev, nxt), encoding="utf-8", newline="\n")
        wanted.add(path.name)
        print(f"wrote {path.relative_to(HERE.parent)}")
    for stale in sorted(p.name for p in OUT.glob("*.qmd") if p.name not in wanted):
        print(f"warning: teaching/lectures/{stale} is not in lectures.yml; delete it")
    print(f"{len(lectures)} lectures OK")


if __name__ == "__main__":
    main()
